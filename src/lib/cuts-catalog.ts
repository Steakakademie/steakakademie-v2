// Cut-DNA — fünf Achsen, jeweils 1–5. Basis für das Radar-Diagramm.
export interface CutDna {
  marbling: number; // Marmorierung / intramuskuläres Fett
  tenderness: number; // Zartheit
  fat: number; // Fettanteil gesamt (inkl. Deckel/Rand)
  flavor: number; // Aroma-Intensität
  value: number; // Preis-Leistung (5 = günstig & dankbar, 1 = teuer/Premium)
}

export interface Cut {
  id: string;
  slug: string; // /cuts/<slug> falls eine MDX-Detailseite existiert
  species: Species;
  primal: string; // Teilstück-ID (siehe PRIMALS)
  nameDE: string;
  nameEN: string;
  aka: string[]; // Synonyme / Handelsnamen
  origin: string; // Lage am Tier (Kurztext)
  blurb: string; // 1–2 Sätze Charakteristik
  facts: string; // Kurzfakt (Gewicht/Verwendung)
  dna: CutDna;
  doneness: string; // empfohlene Garstufe
  coreTemp: string; // Kerntemperatur-Empfehlung
  methods: CookMethod[]; // geeignete Garmethoden
  level: number; // Schwierigkeit 1 (Anfänger) – 5 (Profi)
  price: number; // Preisniveau 1 (günstig) – 5 (Premium)
  occasions: Occasion[]; // wofür eignet sich der Cut
  meatTypeMatch: string[]; // Substrings → Mapping auf Rezept-`meatType` (lowercase)
  image: string; // /images/cuts/<slug>.jpg
  visualBrief: string; // EN-Briefing für die FLUX-Bildgenerierung
  hasGuide?: boolean; // true = es gibt eine ausführliche /cuts/<slug>-Seite
  /**
   * true = Bild wurde generativ ERZEUGT oder WESENTLICH VERÄNDERT und wird im
   * Atlas gekennzeichnet (BildCredit/CutImage). Maßstab wie in BildCredit.tsx:
   * reine Farb- und Tonwertkorrektur löst die Kennzeichnung NICHT aus.
   *
   * Der serienweite Ablauf aus `public/images/cuts/CREDITS.md` (Umgebung per
   * nano-banana-pro/edit entfernt, danach einheitliches Studio-Relight) lässt die
   * Anatomie unverändert und gilt deshalb als Bildbearbeitung, nicht als
   * Erzeugung. Gekennzeichnet werden die beiden Fußnoten-Fälle: `porterhouse`
   * (vollständig KI-erzeugt) und `roastbeef`/rumpsteak (Marmorierung ergänzt).
   */
  imageAI?: boolean;
  /** Klartext-Herkunft wie im MDX-Frontmatter; Format siehe BildCredit.tsx. */
  imageSource?: string;
}

