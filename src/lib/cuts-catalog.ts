export const ALL_CUTS: Cut[] = [...BEEF_CUTS, ...PORK_CUTS];
export const ALL_PRIMALS: Primal[] = [...BEEF_PRIMALS, ...PORK_PRIMALS];

export function getCutsBySpecies(species: Species): Cut[] {
  return ALL_CUTS.filter((c) => c.species === species);
}

export function getPrimalsBySpecies(species: Species): Primal[] {
  return ALL_PRIMALS.filter((p) => p.species === species);
}

export function getCutById(id: string): Cut | undefined {
  return ALL_CUTS.find((c) => c.id === id);
}

export function getCutsByPrimal(primalId: string): Cut[] {
  return ALL_CUTS.filter((c) => c.primal === primalId);
}

