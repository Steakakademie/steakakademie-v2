export type Species = 'rind' | 'schwein';

// Garmethoden — Schlüssel für Generator-Matching + Anzeige
export type CookMethod =
  | 'grill-direkt'
  | 'grill-indirekt'
  | 'pfanne'
  | 'smoker'
  | 'sous-vide'
  | 'schmoren'
  | 'ofen';

